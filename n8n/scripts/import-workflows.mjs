// Imports every workflow in n8n/workflows/ into the running n8n, and activates the ones
// whose JSON says `"active": true`.
//
// The repo is the source of truth for workflows; n8n is only the runtime (ADR 0010).
// This script is what makes that true in practice — and it is the reason guesting in a
// shared n8n is safe: if the instance is ever destroyed, one command rebuilds our half.
//
// Uses the n8n CLI inside the container, so no N8N_API_KEY is needed.
//
// Usage:  node n8n/scripts/import-workflows.mjs [container-name]

import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { takeExclusive } from '../../exclusive.mjs';

// ONE MUTATOR AT A TIME (BUG-054).
// This script deploys every workflow into n8n — so a second copy of it, or a `check-all` sweep
// running beside it, interleaves, and each reports the other's cleanup as its own defect.
// Inside a sweep that already holds the lock this is a no-op.
takeExclusive('n8n/scripts/import-workflows.mjs', {
  files: ['n8n/workflows/*.json (into the container)'],
});

const CONTAINER = process.argv[2] ?? process.env.N8N_CONTAINER ?? 'n8n-local';
const DIR = 'n8n/workflows';

const docker = (args) => execFileSync('docker', args, { encoding: 'utf8' });

const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
if (!files.length) {
  console.error(`No workflow JSON in ${DIR}.`);
  process.exit(1);
}

// PER-MACHINE OVERRIDES (E9-S1). A credential id is generated by each n8n instance, so the
// committed workflow cannot name one without the repository carrying a handle into somebody's
// server. `bind-provider-credential.mjs` writes the bound copy here instead; this directory is
// gitignored and usually holds exactly one file, WF0's.
//
// It is REPORTED on every import rather than applied silently: "which file did n8n actually
// get" is the question that costs an afternoon when the answer is a surprise.
const LOCAL_DIR = 'n8n/workflows.local';

let failed = 0;
for (const file of files) {
  const override = join(LOCAL_DIR, file);
  const usingOverride = existsSync(override);
  const path = usingOverride ? override : join(DIR, file);
  if (usingOverride) console.log(`      ${file}: using the local credential binding from ${LOCAL_DIR}/`);
  const wf = JSON.parse(readFileSync(path, 'utf8'));
  if (!wf.id) {
    console.error(`FAIL  ${file}: no "id". n8n's importer requires one, and a stable id is`);
    console.error('      what makes re-import an update rather than a duplicate.');
    failed++;
    continue;
  }
  try {
    docker(['cp', path, `${CONTAINER}:/tmp/${file}`]);
    // --activeState=fromJson honours each workflow's own `active` field; the default
    // silently deactivates everything it imports.
    // `--activeState=fromJson` is refused in regular (non-queue) deployment mode, so
    // import always deactivates and activation is a separate step below.
    const out = docker(['exec', CONTAINER, 'sh', '-c',
      `n8n import:workflow --input=/tmp/${file} 2>&1 | tail -2`]);
    const okLine = /Successfully imported/.test(out);
    if (okLine && wf.active === true) {
      docker(['exec', CONTAINER, 'sh', '-c',
        `n8n update:workflow --id=${wf.id} --active=true 2>&1 | tail -1`]);
    }
    // `docker cp` lands the file as root while n8n runs as `node`, so removing it can be
    // refused. That is tidiness, not correctness — it must never fail the import.
    try { docker(['exec', CONTAINER, 'sh', '-c', `rm -f /tmp/${file}`]); }
    catch { console.warn(`      (left /tmp/${file} in the container; harmless)`); }
    console.log(`${okLine ? 'OK  ' : 'FAIL'}  ${file}  (${wf.id}, active=${wf.active === true})`);
    if (!okLine) { process.stdout.write(out.replace(/^/gm, '        ')); failed++; }
  } catch (err) {
    console.error(`FAIL  ${file}: ${err.message}`);
    failed++;
  }
}

console.log(`\n${files.length - failed}/${files.length} imported`);
if (failed) process.exit(1);
console.log('Restart n8n so activation and webhooks take effect:');
console.log(`  docker restart ${CONTAINER}`);
